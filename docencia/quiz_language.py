def diagnostic(message, **values):
    template = _DIAGNOSTICS[message] if current_language() == "en" else message
    return template.format(**values)


class QuizText:
    def __init__(self, language="es"):
        if language not in ("es", "en"):
            raise ValueError("Expected language es or en.")
        self.language = language

    def __call__(self, source):
        return _TEXT[source] if self.language == "en" else source


def model_options(source, language):
    """GIFT true/false labels are supplied by the renderer, even with feedback."""
    options = source.get("options", [])
    if source["type"] != "truefalse":
        return options
    label = QuizText(language)
    return [
        {**(options[i] if options else {}), "text": label(text),
         "weight": 100 if truth == source["true_answer"] else 0}
        for i, (truth, text) in enumerate(((True, "Verdadero"), (False, "Falso")))
    ]
